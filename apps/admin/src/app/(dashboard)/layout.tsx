export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  const router = useRouter();
  const pathname = usePathname();

  useEffect(() => {
    if (!localStorage.getItem('accessToken')) {
      router.push('/login');
    }
  }, []);

  const logout = () => {
    localStorage.removeItem('accessToken');
    router.push('/login');
  };

  const isActive = (href: string) =>
    pathname === href || (href !== '/dashboard' && pathname.startsWith(href + '/'));

  return (
    <div className="app-shell">
      <aside className="sidebar">
        {/* Signature: 3px gradient accent strip */}
        <div className="sidebar-accent" />

        {/* Brand */}
        <div className="sidebar-brand">
          <div className="brand-icon">{Icon.hub}</div>
          <div>
            <div className="brand-name">LINE Hub</div>
            <div className="brand-sub">商家管理後台</div>
          </div>
        </div>

        {/* Navigation */}
        <nav className="sidebar-nav">
          <div className="nav-group-label">主要功能</div>
          {MAIN_NAV.map(({ href, label, icon }) => (
            <Link
              key={href}
              href={href}
              className={`nav-link${isActive(href) ? ' active' : ''}`}
            >
              <span className="nav-link-icon">{icon}</span>
              <span>{label}</span>
            </Link>
          ))}

          <hr className="nav-divider" />
          <div className="nav-group-label">設定</div>

          {SETTINGS_NAV.map(({ href, label, icon }) => (
            <Link
              key={href}
              href={href}
              className={`nav-link${isActive(href) ? ' active' : ''}`}
            >
              <span className="nav-link-icon">{icon}</span>
              <span>{label}</span>
            </Link>
          ))}
        </nav>

        {/* Footer */}
        <div className="sidebar-footer">
          <button onClick={logout} className="logout-btn">
            {Icon.logout}
            <span>登出</span>
          </button>
        </div>
      </aside>

      <main className="main-area">
        {children}
      </main>
    </div>
  );
}
